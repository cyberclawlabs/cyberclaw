function tFor(lang) {
  return (k, vars) => {
    let s = (STRINGS[lang] && STRINGS[lang][k]) || STRINGS.en[k] || k;
    if (vars) {
      for (const [vk, vv] of Object.entries(vars)) {
        s = s.replace(new RegExp('\\{' + vk + '\\}', 'g'), vv);
      }
    }
    return s;
  };
}

